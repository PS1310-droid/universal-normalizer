# =====================================================================
# STEP 3: VISUAL TERMINAL DASHBOARD ENGINE
# =====================================================================
def display_terminal_dashboard(title, response_data):
    """
    An administrative visual helper tool. Instead of printing a chaotic, unreadable
    raw text blob, this function unpacks the JSON server payload and translates it
    into a structured, executive-level telemetry report directly inside the terminal console.
    """
    print("\n" + "═" * 68)
    print(f" 📊 {title}")
    print("═" * 68)

    # Isolate the data buckets processed by the serverless framework
    ready = response_data.get("ready_to_use", {})
    flagged = response_data.get("flagged_for_review", {})

    # Display core operation statistics
    print(f" NETWORK STATUS : 🟢 Connected & Authenticated Successfully")
    print(
        f" PIPELINE METRICS: {len(ready)} Keys Resolved | {len(flagged)} Conflicts Transferred"
    )
    print("─" * 68)

    # SECTION A: Display cleanly normalized variables ready to append to target DB structures
    print(" ✅ READY TO USE (Automated Production Pipeline Output):")
    if not ready:
        print(
            "    [Notice] Zero values passed the automated mapping confidence threshold."
        )
    else:
        for target_key, value in ready.items():
            # Using python formatting constraints (<22) to align columns symmetrically
            print(f"    ▶ {target_key:<22} ➔   {str(value)}")

    # SECTION B: Display structural data points that require human audit due to low structural affinity
    print("\n ⚠️ FLAGGED FOR REVIEW (Low Confidence/Structural Gaps Captured):")
    if not flagged:
        print("    [Clear] No schema conflicts detected in this operation batch.")
    else:
        for target_key, details in flagged.items():
            suggestion = details.get("suggested_match")
            confidence = details.get("confidence_score", 0)
            display_suggest = f"'{suggestion}'" if suggestion else "None Detected"
            print(
                f"    ▶ {target_key:<22} [Proposed Source: {display_suggest:<15} | Affinity: {confidence}%]"
            )

    # SECTION C: Expose the system's explicit decision logic path for internal developer diagnostics
    print("\n 📜 INTERNAL API ARCHITECTURE AUDIT LOGS:")
    for log in response_data.get("audit_log", []):
        print(f"    • {log}")
    print("═" * 68 + "\n")


